// Writes the Firestore/Storage rules for a non-production environment.
//
// The committed firestore.rules / storage.rules ARE the production rules.
// They pin production values that differ elsewhere:
// - the Storage download host `https://firebasestorage.googleapis.com`
//   (the Storage emulator serves `http://localhost:9199` /
//   `http://127.0.0.1:9199`);
// - the production bucket `touchgrass-today.firebasestorage.app` (profile
//   photos).
// This tool makes exactly those substitutions — each pattern must occur the
// expected number of times, or it fails — and nothing else, so dev and
// emulator runs test the real authorization logic.
//
//   node tool/rules_for_env.mjs <development|emulator> <outDir>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const PROD_BUCKET = 'touchgrass-today.firebasestorage.app';
export const DEV_PROJECT = 'touchgrass-dev-n7j3f';
export const EMULATOR_PROJECT = 'demo-touchgrass-dev';

export const ENVIRONMENTS = {
  development: { bucket: `${DEV_PROJECT}.firebasestorage.app`, emulatorHost: false },
  emulator: { bucket: `${EMULATOR_PROJECT}.appspot.com`, emulatorHost: true },
};

const HOST_RULE = "https://firebasestorage[.]googleapis[.]com";
const EMULATOR_HOST_RULE = "(https://firebasestorage[.]googleapis[.]com|http://(localhost|127[.]0[.]0[.]1):9199)";
const rulesBucket = (b) => b.replaceAll('.', '[.]');

function replaceExactly(text, from, to, expected, label) {
  const n = text.split(from).length - 1;
  if (n !== expected) throw new Error(`${label}: expected ${expected} occurrence(s) of the pattern, found ${n}`);
  return text.split(from).join(to);
}

/** The Firestore rules for [env], from the production [source]. */
export function firestoreRulesFor(env, source) {
  const cfg = ENVIRONMENTS[env];
  if (!cfg) throw new Error(`unknown environment: ${env}`);
  let out = replaceExactly(source, `'${HOST_RULE}/v0/b/'\n                  + '${rulesBucket(PROD_BUCKET)}/o/user_avatars%2F'`,
    `'${cfg.emulatorHost ? EMULATOR_HOST_RULE : HOST_RULE}/v0/b/'\n                  + '${rulesBucket(cfg.bucket)}/o/user_avatars%2F'`,
    1, 'profile-photo URL');
  if (cfg.emulatorHost) {
    out = replaceExactly(out, `'${HOST_RULE}/v0/b/[^/]+/o/completion_photos%2F'`,
      `'${EMULATOR_HOST_RULE}/v0/b/[^/]+/o/completion_photos%2F'`, 1, 'completion photo URL');
  }
  if (out.includes(PROD_BUCKET) || out.includes(rulesBucket(PROD_BUCKET))) {
    throw new Error('the production bucket is still referenced');
  }
  return `// GENERATED by tool/rules_for_env.mjs for "${env}" — do not edit or deploy to production.\n${out}`;
}

/** Storage rules reference no environment-specific value; checked anyway. */
export function storageRulesFor(env, source) {
  if (!ENVIRONMENTS[env]) throw new Error(`unknown environment: ${env}`);
  if (source.includes(PROD_BUCKET) || source.includes('firebasestorage.googleapis')) {
    throw new Error('storage.rules gained an environment-specific value; extend tool/rules_for_env.mjs');
  }
  return `// GENERATED by tool/rules_for_env.mjs for "${env}" — do not edit or deploy to production.\n${source}`;
}

function main([env, outDir]) {
  if (!env || !outDir) throw new Error('usage: node tool/rules_for_env.mjs <development|emulator> <outDir>');
  fs.mkdirSync(outDir, { recursive: true });
  const fsRules = firestoreRulesFor(env, fs.readFileSync(path.join(root, 'firestore.rules'), 'utf8'));
  const stRules = storageRulesFor(env, fs.readFileSync(path.join(root, 'storage.rules'), 'utf8'));
  fs.writeFileSync(path.join(outDir, `firestore.${env}.rules`), fsRules);
  fs.writeFileSync(path.join(outDir, `storage.${env}.rules`), stRules);
  // Indexes are environment-independent; copied because the Firebase CLI
  // only reads files inside the config file's own folder.
  fs.copyFileSync(path.join(root, 'firestore.indexes.json'), path.join(outDir, 'firestore.indexes.json'));
  console.log(`wrote ${env} rules to ${outDir}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main(process.argv.slice(2));
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
